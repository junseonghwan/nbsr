"""Paired permutation benchmark on the immune data (43 patients with both Pre and On samples).

The null is generated by swapping the Pre/On labels within each patient with probability 1/2, which keeps
the patient structure intact. Each permutation is analysed with
  * fnb unpaired : mean ~trt,            dispersion ~trt   (model-based and sandwich SE)
  * fnb paired   : mean ~patient + trt,  dispersion ~trt   (model-based and sandwich SE)
  * DESeq2 unpaired (~trt) and paired (~patient + trt)
Permutation 0 is the observed labels. Usage: python scripts/permutation_benchmark_paired.py [n_perm] [seed] [out_dir]
Outputs to data/immune_data/permutation_paired/.
"""
import sys, time
from pathlib import Path
import numpy as np, pandas as pd, torch, anndata as ad, scipy.stats as ss
from pydeseq2.dds import DeseqDataSet
from pydeseq2.ds import DeseqStats
from pydeseq2.default_inference import DefaultInference
from nbsr.dataset import Dataset
from nbsr.fnb_stats import FeaturewiseNBStats

N_PERM = int(sys.argv[1]) if len(sys.argv) > 1 else 10
SEED   = int(sys.argv[2]) if len(sys.argv) > 2 else 1
N_CPUS = 8
OUT = Path(sys.argv[3]) if len(sys.argv) > 3 else Path("data/immune_data/permutation_paired")
OUT.mkdir(parents=True, exist_ok=True)
torch.set_num_threads(N_CPUS)
PRIORS = dict(b_prior_sd=0.5, gamma_prior_sd=1.0)

adata = ad.read_h5ad("data/immune_data/dataset.h5ad")
meta_all = pd.read_csv("data/immune_data/X_paired.csv", index_col="sample_name").loc[adata.obs_names]
tab = pd.crosstab(meta_all.patient, meta_all.trt)
paired_patients = tab.index[(tab.Pre == 1) & (tab.On == 1)]
keep = meta_all.patient.isin(paired_patients)
counts = pd.DataFrame(np.asarray(adata.X), index=adata.obs_names, columns=adata.var_names).loc[keep]
meta0 = meta_all.loc[keep, ["patient", "trt"]].copy()
print(f"{len(paired_patients)} patients, {len(counts)} samples, {counts.shape[1]} genes", flush=True)
G = counts.shape[1]
rng = np.random.default_rng(SEED)

DESIGNS = {"unpaired": "~trt", "paired": "~patient + trt"}
METHODS = [f"fnb_{d}{s}" for d in DESIGNS for s in ("", "_robust")] + [f"deseq2_{d}" for d in DESIGNS]
pvals = {m: np.full((N_PERM + 1, G), np.nan) for m in METHODS}
rows = []

def summarize(method, perm, p, padj, extra=None):
    ok = np.isfinite(p)
    row = dict(perm=perm, method=method, n_tested=int(ok.sum()),
               n_padj05=int(np.nansum(padj < 0.05)), n_padj10=int(np.nansum(padj < 0.10)),
               frac_p05=float(np.mean(p[ok] < 0.05)), ks_stat=float(ss.kstest(p[ok], "uniform").statistic))
    row.update(extra or {}); rows.append(row)
    print(f"  {method:22s} padj<.05: {row['n_padj05']:5d}  padj<.10: {row['n_padj10']:5d}  "
          f"frac p<.05: {row['frac_p05']:.3f}  KS: {row['ks_stat']:.3f}", flush=True)

for perm in range(N_PERM + 1):
    meta = meta0.copy()
    if perm > 0:
        swap = pd.Series(rng.random(len(paired_patients)) < 0.5, index=paired_patients)
        flip = meta.patient.map(swap).to_numpy()
        meta["trt"] = np.where(flip, np.where(meta.trt == "Pre", "On", "Pre"), meta.trt)
    meta["trt"] = pd.Categorical(meta["trt"], categories=["Pre", "On"])
    meta["patient"] = pd.Categorical(meta["patient"])
    print(f"=== permutation {perm} ({'observed' if perm == 0 else 'within-patient swap'}) ===", flush=True)

    for design, formula in DESIGNS.items():
        t0 = time.time()
        ds = Dataset(counts, meta, mean_formula=formula, disp_formula="~trt", n_cpus=N_CPUS)
        st = FeaturewiseNBStats(ds, **PRIORS); st.fit(method="newton")
        t_fit = round(time.time() - t0, 1)
        for suffix, robust in [("", False), ("_robust", True)]:
            res = st.results("trt", reference_level="Pre", test_level="On", robust=robust)
            name = f"fnb_{design}{suffix}"
            pvals[name][perm] = res["pval"].to_numpy()
            summarize(name, perm, res["pval"].to_numpy(), res["padj"].to_numpy(),
                      dict(n_converged=int(res["converged"].sum()), seconds=t_fit))
        t0 = time.time()
        dds = DeseqDataSet(counts=counts, metadata=meta, design=formula, inference=DefaultInference(n_cpus=N_CPUS), quiet=True)
        dds.deseq2()
        stat = DeseqStats(dds, contrast=["trt", "On", "Pre"], inference=DefaultInference(n_cpus=N_CPUS), quiet=True)
        stat.summary()
        df = stat.results_df.reindex(counts.columns)
        name = f"deseq2_{design}"
        pvals[name][perm] = df["pvalue"].to_numpy()
        summarize(name, perm, df["pvalue"].to_numpy(), df["padj"].to_numpy(),
                  dict(n_converged=int(df["pvalue"].notna().sum()), seconds=round(time.time() - t0, 1)))

    pd.DataFrame(rows).to_csv(OUT / "summary.csv", index=False)
    for m, arr in pvals.items():
        np.save(OUT / f"pvalues_{m}.npy", arr)
print("done", flush=True)
